// UART receiver and transmitter used by verilog_uart.py (8N1, mid-bit sampling).
module uart_rx #(
    parameter CLKS_PER_BIT = 234            // 27 MHz / 115200
) (
    input  wire       clk,
    input  wire       rx,
    output reg  [7:0] data   = 0,
    output reg        strobe = 0            // one clock, byte received with good stop bit
);
    reg rx_m = 1'b1, rx_s = 1'b1;           // 2-flop synchronizer
    always @(posedge clk) begin rx_m <= rx; rx_s <= rx_m; end

    localparam IDLE = 0, START = 1, DATA = 2, STOP = 3;
    reg [1:0]  st  = IDLE;
    reg [15:0] cnt = 0;
    reg [2:0]  bi  = 0;

    always @(posedge clk) begin
        strobe <= 1'b0;
        case (st)
            IDLE: if (!rx_s) begin cnt <= 0; st <= START; end
            START: if (cnt == CLKS_PER_BIT / 2 - 1) begin   // middle of start bit
                if (!rx_s) begin cnt <= 0; bi <= 0; st <= DATA; end
                else st <= IDLE;
            end else cnt <= cnt + 1;
            DATA: if (cnt == CLKS_PER_BIT - 1) begin        // middle of each data bit
                cnt  <= 0;
                data <= {rx_s, data[7:1]};                  // LSB first
                bi   <= bi + 1;
                if (bi == 7) st <= STOP;
            end else cnt <= cnt + 1;
            STOP: if (cnt == CLKS_PER_BIT - 1) begin
                strobe <= rx_s;
                st <= IDLE;
            end else cnt <= cnt + 1;
        endcase
    end
endmodule

module uart_tx #(
    parameter CLKS_PER_BIT = 234
) (
    input  wire       clk,
    input  wire [7:0] data,
    input  wire       start,                // one clock, ignored while busy
    output reg        tx   = 1'b1,
    output wire       busy
);
    reg [9:0]  sh     = 10'h3ff;            // {stop 1, byte, start 0}
    reg [15:0] cnt    = 0;
    reg [3:0]  bi     = 0;
    reg        active = 1'b0;
    assign busy = active;

    always @(posedge clk) begin
        if (!active) begin
            tx <= 1'b1;
            if (start) begin sh <= {1'b1, data, 1'b0}; cnt <= 0; bi <= 0; active <= 1'b1; end
        end else begin
            tx <= sh[0];
            if (cnt == CLKS_PER_BIT - 1) begin
                cnt <= 0;
                sh  <= {1'b1, sh[9:1]};
                bi  <= bi + 1;
                if (bi == 9) active <= 1'b0;
            end else cnt <= cnt + 1;
        end
    end
endmodule



// UART front end for cmtz_core: F_17, q = 19, ISA version 1.
// Generated by cmtz/backends/isa_uart.py; protocol in cmtz/isa/host.py.
// LEDs (active low): 0 running, 1 halted, 2 error, 3 toggles per
// interrupt, 4 program loaded, 5 last reply was an error.
module cmtz_core_uart #(
    parameter CLKS_PER_BIT = 234,           // 27 MHz / 115200
    parameter TIMEOUT_CLKS = 2700000        // 100 ms
) (
    input  wire       clk,
    input  wire       rx,
    output wire       tx,
    output wire [5:0] leds
);

wire [7:0] rx_data;
wire       rx_stb;
reg  [7:0] tx_data = 8'd0;
reg        tx_start = 1'b0;
wire       tx_busy;
uart_rx #(.CLKS_PER_BIT(CLKS_PER_BIT)) u_rx (
    .clk(clk), .rx(rx), .data(rx_data), .strobe(rx_stb));
uart_tx #(.CLKS_PER_BIT(CLKS_PER_BIT)) u_tx (
    .clk(clk), .data(tx_data), .start(tx_start), .tx(tx), .busy(tx_busy));

reg start = 1'b0, abort = 1'b0, irq = 1'b0;
reg [9:0] cfg_len = 10'd0, cfg_entry = 10'd0, cfg_handler = 10'd0;
reg cfg_has_handler = 1'b0;
reg pm_we = 1'b0;
reg [8:0] pm_addr = 9'd0;
reg [31:0] pm_wdata = 32'd0;
reg dm_we = 1'b0;
reg [9:0] dm_addr = 10'd0;
reg [4:0] dm_wdata = 5'd0;
wire [4:0] dm_rdata;
reg r_we = 1'b0;
reg [4:0] r_addr = 5'd0;
reg [4:0] r_wdata = 5'd0;
wire [4:0] r_rdata;
reg [3:0] x_addr = 4'd0;
wire [15:0] x_rdata;
wire [1:0] status;
wire [2:0] error;
wire [31:0] retired, disp_retired;
wire [9:0] disp_pc, pc_out;
wire [15:0] disp_count;
wire boundary;

cmtz_core core (
    .clk(clk), .start(start), .abort(abort), .irq(irq),
    .cfg_len(cfg_len), .cfg_entry(cfg_entry), .cfg_handler(cfg_handler),
    .cfg_has_handler(cfg_has_handler),
    .pm_we(pm_we), .pm_addr(pm_addr), .pm_wdata(pm_wdata),
    .dm_we(dm_we), .dm_addr(dm_addr), .dm_wdata(dm_wdata), .dm_rdata(dm_rdata),
    .r_we(r_we), .r_addr(r_addr), .r_wdata(r_wdata), .r_rdata(r_rdata),
    .x_addr(x_addr), .x_rdata(x_rdata),
    .status(status), .error(error), .retired(retired),
    .disp_retired(disp_retired), .disp_pc(disp_pc), .disp_count(disp_count),
    .boundary(boundary), .pc_out(pc_out));

wire running = (status == 2'd1);

function [31:0] crc8;                       // zlib crc32, one byte
    input [31:0] c;
    input [7:0]  d;
    integer k;
    reg [31:0] x;
    begin
        x = c ^ {24'd0, d};
        for (k = 0; k < 8; k = k + 1)
            x = x[0] ? ((x >> 1) ^ 32'hEDB88320) : (x >> 1);
        crc8 = x;
    end
endfunction

localparam C_WAIT = 3'd0, C_ARGS = 3'd1, C_EXEC = 3'd2, C_STREAM = 3'd3,
           C_DONE = 3'd4, C_REPLY = 3'd5;
localparam R_SET = 3'd0, R_S1 = 3'd1, R_S2 = 3'd2, R_SEND = 3'd3,
           R_HOLD = 3'd4, R_WAIT = 3'd5;

reg [2:0]  cs = C_WAIT;
reg [2:0]  rs = R_SET;
reg [7:0]  cmd = 8'd0;
reg [7:0]  arg0 = 8'd0, arg1 = 8'd0, arg2 = 8'd0, arg3 = 8'd0,
           arg4 = 8'd0, arg5 = 8'd0;
reg [2:0]  argi = 3'd0, nargs = 3'd0;
reg [31:0] tcount = 32'd0;
reg [15:0] cnt = 16'd0;
reg [15:0] idx = 16'd0;
reg [15:0] rlen = 16'd0;
reg [1:0]  bsel = 2'd0;
reg        ok = 1'b0, bad = 1'b0, err_led = 1'b0;
reg [7:0]  code = 8'd0;
reg [31:0] crc = 32'hFFFFFFFF;
reg [31:0] words_crc = 32'd0;
reg [127:0] snap = 128'd0;

wire [15:0] a01 = {arg0, arg1};
wire [15:0] a23 = {arg2, arg3};
wire [15:0] a45 = {arg4, arg5};
wire [16:0] dm_end = {1'b0, a01} + {1'b0, a23};

wire [167:0] info = {120'h434d544301111302000400ad918bbc, {6'd0, cfg_len}, words_crc};
wire [39:0]  p_reply = ok ? {8'h00, words_crc} : 40'hFFFFFFFFFF;

reg [7:0] rbyte;
always @* begin
    case (cmd)
    "M":     rbyte = ok ? {3'd0, dm_rdata} : 8'hFF;
    "S":     rbyte = !ok ? 8'hFF :
                     (idx < 16'd32) ? {3'd0, r_rdata} :
                     (idx[0] ? x_rdata[7:0] : x_rdata[15:8]);
    "Q":     rbyte = snap[127 - 8 * idx[3:0] -: 8];
    "I":     rbyte = info[167 - 8 * idx[4:0] -: 8];
    "P":     rbyte = p_reply[39 - 8 * idx[2:0] -: 8];
    default: rbyte = code;
    endcase
end

always @(posedge clk) begin
    start <= 1'b0; abort <= 1'b0; irq <= 1'b0;
    pm_we <= 1'b0; dm_we <= 1'b0; r_we <= 1'b0; tx_start <= 1'b0;
    case (cs)
    C_WAIT: if (rx_stb) begin
        cmd <= rx_data; argi <= 3'd0; tcount <= 32'd0;
        case (rx_data)
        "P":         begin nargs <= 3'd6; cs <= C_ARGS; end
        "W":         begin nargs <= 3'd2; cs <= C_ARGS; end
        "D", "M":    begin nargs <= 3'd4; cs <= C_ARGS; end
        "I", "S", "G", "Q", "T", "X": cs <= C_EXEC;
        default: ;
        endcase
    end
    C_ARGS: if (rx_stb) begin
        case (argi)
        3'd0: arg0 <= rx_data;
        3'd1: arg1 <= rx_data;
        3'd2: arg2 <= rx_data;
        3'd3: arg3 <= rx_data;
        3'd4: arg4 <= rx_data;
        default: arg5 <= rx_data;
        endcase
        argi <= argi + 3'd1;
        tcount <= 32'd0;
        if (argi + 3'd1 == nargs) cs <= C_EXEC;
    end else if (tcount >= TIMEOUT_CLKS) cs <= C_WAIT;
    else tcount <= tcount + 32'd1;
    C_EXEC: begin
        idx <= 16'd0; rs <= R_SET; rlen <= 16'd1; bad <= 1'b0; tcount <= 32'd0;
        cs <= C_REPLY;
        case (cmd)
        "P": begin
            ok <= !running && a01 != 16'd0 && a01 <= 16'd512
                  && a23 < a01 && (a45 == 16'hFFFF || a45 < a01);
            cnt <= a01; bsel <= 2'd0; crc <= 32'hFFFFFFFF; rlen <= 16'd5;
            cs <= (a01 == 16'd0) ? C_DONE : C_STREAM;
        end
        "D": begin
            ok <= !running && dm_end <= 17'd1024;
            cnt <= a23;
            cs <= (a23 == 16'd0) ? C_DONE : C_STREAM;
        end
        "W": if (!running && arg0 < 8'd32 && arg1 < 8'd19) begin
            r_addr <= arg0[4:0]; r_wdata <= arg1[4:0]; r_we <= 1'b1;
            code <= 8'h00;
        end else code <= 8'hFF;
        "M": begin
            ok <= !running && dm_end <= 17'd1024;
            rlen <= a23;
            if (a23 == 16'd0) cs <= C_WAIT;
        end
        "S": begin ok <= !running; rlen <= 16'd64; end
        "Q": begin
            snap <= {6'd0, status, 5'd0, error, retired, disp_count, disp_retired,
                     {6'd0, disp_pc}, {6'd0, pc_out}};
            rlen <= 16'd16;
        end
        "I": rlen <= 16'd21;
        "G": if (!running && cfg_len != 10'd0) begin
            start <= 1'b1; code <= 8'h00;
        end else code <= 8'hFF;
        "T": begin irq <= 1'b1; code <= 8'h00; end
        default: begin abort <= 1'b1; code <= 8'h00; end      // "X"
        endcase
    end
    C_STREAM: if (rx_stb) begin
        tcount <= 32'd0;
        if (cmd == "P") begin
            pm_wdata <= {pm_wdata[23:0], rx_data};
            crc <= crc8(crc, rx_data);
            bsel <= bsel + 2'd1;
            if (bsel == 2'd3) begin
                pm_addr <= idx[8:0];
                pm_we <= ok;
                idx <= idx + 16'd1;
                cnt <= cnt - 16'd1;
                if (cnt == 16'd1) cs <= C_DONE;
            end
        end else begin                                         // "D"
            dm_addr <= a01[9:0] + idx[9:0];
            dm_wdata <= rx_data[4:0];
            dm_we <= ok && rx_data < 8'd19;
            if (rx_data >= 8'd19) bad <= 1'b1;
            idx <= idx + 16'd1;
            cnt <= cnt - 16'd1;
            if (cnt == 16'd1) cs <= C_DONE;
        end
    end else if (tcount >= TIMEOUT_CLKS) cs <= C_WAIT;
    else tcount <= tcount + 32'd1;
    C_DONE: begin
        idx <= 16'd0; rs <= R_SET;
        if (cmd == "P") begin
            if (ok) begin
                cfg_len <= a01[9:0];
                cfg_entry <= a23[9:0];
                cfg_handler <= a45[9:0];
                cfg_has_handler <= (a45 != 16'hFFFF);
                words_crc <= ~crc;
            end
        end else begin
            code <= (ok && !bad) ? 8'h00 : 8'hFF;
            rlen <= 16'd1;
        end
        cs <= C_REPLY;
    end
    default: case (rs)                                         // C_REPLY
        R_SET: begin
            dm_addr <= a01[9:0] + idx[9:0];
            r_addr <= idx[4:0];
            x_addr <= idx[4:1];         // idx 32 + 2i + b -> X[i]
            rs <= R_S1;
        end
        R_S1: rs <= R_S2;
        R_S2: rs <= R_SEND;
        R_SEND: if (!tx_busy) begin
            tx_data <= rbyte; tx_start <= 1'b1; rs <= R_HOLD;
            if (idx == 16'd0) err_led <= (rbyte == 8'hFF);
        end
        R_HOLD: rs <= R_WAIT;
        default: if (!tx_busy) begin
            if (idx + 16'd1 >= rlen) cs <= C_WAIT;
            else begin idx <= idx + 16'd1; rs <= R_SET; end
        end
    endcase
    endcase
end

assign leds = ~{err_led, cfg_len != 10'd0, disp_count[0],
                status == 2'd3, status == 2'd2, running};

endmodule

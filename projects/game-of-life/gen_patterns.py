#!/usr/bin/env python3
"""Writes life_pat_rom.v: the hand-drawn seed patterns as a combinational ROM.

Run from this folder: python3 gen_patterns.py
Column 0 of a pattern is bit 0 of the row word, which is the leftmost cell on screen.
"""

# kind -> (name, x0, y0, rows). Kinds missing here are random seeds made in life_row_core.v.
PATTERNS = {
    0: ("R-pentomino", 79, 44, [
        ".##",
        "##.",
        ".#.",
    ]),
    2: ("acorn", 76, 44, [
        ".#.....",
        "...#...",
        "##..###",
    ]),
    3: ("Gosper glider gun", 10, 10, [
        "........................#...........",
        "......................#.#...........",
        "............##......##............##",
        "...........#...#....##............##",
        "##........#.....#...##..............",
        "##........#...#.##....#.#...........",
        "..........#.....#.......#...........",
        "...........#...#....................",
        "............##......................",
    ]),
    5: ("diehard", 76, 44, [
        "......#.",
        "##......",
        ".#...###",
    ]),
    6: ("pi-heptomino", 79, 44, [
        "###",
        "#.#",
        "#.#",
    ]),
}

PW = 40     # widest pattern is 36


def main():
    out = []
    out.append("// Generated by gen_patterns.py. Do not edit; change the script and rerun it.")
    out.append("//")
    out.append("// Seed patterns for life_row_core: for a seed kind, where the pattern sits (x0, y0), how many")
    out.append("// rows it has (h), and row `prow` of it. Kinds with h = 0 are random seeds made in the core.")
    out.append("module life_pat_rom (")
    out.append("    input  wire [2:0]      kind,")
    out.append("    input  wire [3:0]      prow,")
    out.append("    output wire [%d:0]     bits," % (PW - 1))
    out.append("    output wire [7:0]      x0,")
    out.append("    output wire [6:0]      y0,")
    out.append("    output wire [3:0]      h")
    out.append(");")
    out.append("    // functions rather than `always @*`, so the outputs are right from time 0 in simulation")
    out.append("    function [18:0] place(input [2:0] k);")
    out.append("        case (k)")
    for k, (name, x0, y0, rows) in sorted(PATTERNS.items()):
        out.append("            3'd%d: place = {8'd%d, 7'd%d, 4'd%d};   // %s"
                   % (k, x0, y0, len(rows), name))
    out.append("            default: place = 19'd0;")
    out.append("        endcase")
    out.append("    endfunction")
    out.append("    assign {x0, y0, h} = place(kind);")
    out.append("    function [%d:0] row(input [6:0] a);" % (PW - 1))
    out.append("        case (a)")
    for k, (name, x0, y0, rows) in sorted(PATTERNS.items()):
        for r, row in enumerate(rows):
            assert len(row) <= PW and set(row) <= set("#.")
            word = "".join("1" if c == "#" else "0" for c in reversed(row)).rjust(PW, "0")
            out.append("            {3'd%d, 4'd%d}: row = %d'b%s;" % (k, r, PW, word))
    out.append("            default: row = %d'b0;" % PW)
    out.append("        endcase")
    out.append("    endfunction")
    out.append("    assign bits = row({kind, prow});")
    out.append("endmodule")
    with open("life_pat_rom.v", "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
